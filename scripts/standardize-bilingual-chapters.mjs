// Helper to translate core chapter name
function translate(title) {
  if (/[\u0900-\u097F]/.test(title)) return title;

  const prefixMatch = title.match(/^(Chapter\s*\d+\s*:\s*)/i);
  const prefix = prefixMatch ? prefixMatch[1] : '';
  const core = title.replace(/^(Chapter\s*\d+\s*:\s*)/i, '').trim();

  const key = core.toLowerCase();
  if (DICTIONARY[key]) {
    return `${prefix}${core} (${DICTIONARY[key]})`;
  }

  // Look for partial key
  for (const [dictKey, hindi] of Object.entries(DICTIONARY)) {
    if (key.includes(dictKey) || dictKey.includes(key)) {
      return `${prefix}${core} (${hindi})`;
    }
  }

  return `${prefix}${core}`;
}

async function main() {
  const isDryRun = process.argv.includes('--dry-run');
  console.log(`Starting Bilingual Standardization (Mode: ${isDryRun ? 'DRY-RUN' : 'LIVE TRANSACTION'})...\n`);

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    const res = await client.query(`
      SELECT id, title
      FROM subject_chapters
      WHERE is_deleted IS NOT TRUE AND title !~ '[\\u0900-\\u097F]'
      ORDER BY id
    `);

    console.log(`Checking ${res.rows.length} chapters currently missing Hindi...`);
    let updates = [];
    let missing = [];

    for (const r of res.rows) {
      const newTitle = translate(r.title);
      if (/[\u0900-\u097F]/.test(newTitle)) {
        updates.push({ id: r.id, title: newTitle });
      } else {
        missing.push(r);
      }
    }

    console.log(`✔ Successfully generated bilingual titles for: ${updates.length} / ${res.rows.length} chapters!`);
    if (missing.length > 0) {
      console.log(`Unmatched chapters count: ${missing.length}`);
      missing.forEach(m => console.log(`   - ID ${m.id}: "${m.title}"`));
    }

    // Batch update using UNNEST
    if (updates.length > 0) {
      const ids = updates.map(u => u.id);
      const titles = updates.map(u => u.title);
      await client.query(`
        UPDATE subject_chapters AS c
        SET title = u.title, updated_at = NOW()
        FROM (SELECT unnest($1::int[]) AS id, unnest($2::text[]) AS title) AS u
        WHERE c.id = u.id
      `, [ids, titles]);
      console.log(`✔ Batch updated ${updates.length} chapters in a single query.`);
    }

    if (isDryRun) {
      await client.query('ROLLBACK');
      console.log('\nDRY-RUN COMPLETE: Changes rolled back cleanly.');
    } else {
      await client.query('COMMIT');
      console.log('\n✔ COMMIT SUCCESSFUL: All chapter titles standardized to bilingual English (हिंदी)!');
    }

  } catch (err) {
    await client.query('ROLLBACK');
    console.error('ERROR during bilingual standardization (rolled back):', err);
    throw err;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
