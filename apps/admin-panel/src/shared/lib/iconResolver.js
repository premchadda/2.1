/**
 * Resolve a Lucide icon by name. Accepts strings like "BookOpen", "trophy",
 * "arrow-up-right", "Trophy", etc., and normalises them to the PascalCase
 * export from the curated icon map. Falls back to a generic Menu icon if the
 * name doesn't match anything we know about so the page never crashes.
 */
const FALLBACK = Menu;
export const resolveLucideIcon = (name) => {
  if (!name || typeof name !== "string") return FALLBACK;
  const pascal = name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1).toLowerCase())
    .join("");
  return ICON_MAP[pascal] || ICON_MAP[name] || FALLBACK;
};
